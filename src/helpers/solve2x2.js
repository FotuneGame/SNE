/**
 * Решение СЛАУ 2×2  M·d = r  методом Крамера.
 * Бросает ошибку, если матрица вырождена.
 */
export function solve2x2(M, r) {
  const det = M[0][0] * M[1][1] - M[0][1] * M[1][0];
  if (Math.abs(det) < 1e-15) {
    throw new Error('Якобиан вырожден, метод не сходится');
  }
  return [
    (r[0] * M[1][1] - M[0][1] * r[1]) / det,
    (M[0][0] * r[1] - M[1][0] * r[0]) / det
  ];
}
